#!/usr/bin/env python3
"""Place kpl-stock-data credentials where the skill can actually read them.

Why this script exists
---------------------
`kpls.config` looks for credentials in this order:

    开盘啦  env KPL_ACCOUNTS_INI  ->  D:\cf\kpl\config\kpl_accounts.ini
                                   ->  <skill>/assets/kpl_accounts.ini
    Tushare env TUSHARE_TOKEN     ->  ini[s:tushare]
                                   ->  D:\cf\趋势分析\.env
                                   ->  <skill>/assets/tushare.token
    平台    env KPL_PY_TOKEN      ->  <skill>/assets/py_token.txt
                                   ->  ini[s:py590]

On the phone the two Windows paths do not exist, and `<skill>/assets` sits
inside `/skills`, which is a read-only mount:

    WorkspaceZone.skills => isWritableZone() == false

So on a phone none of the fallbacks can be written. The fix is to copy the
skill into a writable zone and put the credentials in the copy. `config.py`
resolves `ASSETS_DIR` from `__file__`, so a copy in `/workspace` finds its own
`assets/` automatically -- no code change, no monkey-patching.

Two supported channels, in order of preference:

  1. Environment variables. Nothing is written to disk, so nothing can leak
     into a backup or a transcript. Set them in Kelivo's Environment panel.
  2. Standard input. Feed a JSON object on stdin; it is written to the copy's
     assets/ with mode 600 and never echoed.

Secrets are never printed. `doctor` style output shows only presence, never
value.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import stat
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, ValueError, OSError):
    pass

# The skills zone is read-only in the sandbox; the workspace zone is not.
SKILLS_ZONE = Path("/skills")
DEFAULT_WORK_ROOT = Path("/workspace")

# Keys this script understands, and the file each one lands in.
FILE_MAP = {
    "kpl_accounts": "kpl_accounts.ini",
    "tushare_token": "tushare.token",
    "py_token": "py_token.txt",
}

ENV_MAP = {
    "kpl_accounts_ini": "KPL_ACCOUNTS_INI",
    "tushare_token": "TUSHARE_TOKEN",
    "py_token": "KPL_PY_TOKEN",
    "kpl_token": "KPL_TOKEN",
    "kpl_user_id": "KPL_USER_ID",
    "kpl_device_id": "KPL_DEVICE_ID",
}


def skill_source() -> Path:
    """Locate the installed skill, wherever the host keeps it."""
    candidates = [Path("/skills/kpl-stock-data")]
    here = Path(__file__).resolve()
    # scripts/ -> <skill>/
    candidates.append(here.parent.parent)
    for cand in candidates:
        if (cand / "scripts").is_dir():
            return cand
    raise SystemExit("kpl-stock-data skill not found (looked in /skills and alongside this script)")


def writable_root() -> Path:
    raw = os.environ.get("KPLS_WORK_ROOT")
    root = Path(raw) if raw else DEFAULT_WORK_ROOT
    try:
        root.mkdir(parents=True, exist_ok=True)
    except OSError:
        pass
    return root


def stage_copy(source: Path, root: Path) -> Path:
    """Copy the skill into a writable zone so `assets/` can hold credentials."""
    dest = root / "kpl-stock-data"
    if dest.exists():
        shutil.rmtree(dest, ignore_errors=True)
    shutil.copytree(source, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    assets = dest / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    return dest


def harden(path: Path) -> None:
    """Owner-only. On the phone this is the only defence for a bearer token."""
    try:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass


def write_secret(path: Path, value: str) -> None:
    path.write_text(value.rstrip() + "\n", encoding="utf-8")
    harden(path)


def build_ini(accounts: list[dict]) -> str:
    """Render the accounts file `config._load_ini_accounts` expects.

    It reads `token` + `user_id` per section and skips anything missing either,
    so the keys below are the exact minimum.
    """
    lines = [
        "# kpl_accounts.ini - generated by setup_credentials.py",
        "# Opening-laha accounts. Keep this file at mode 600.",
        "",
    ]
    for index, acc in enumerate(accounts, 1):
        section = (acc.get("name") or f"account_{index}").strip()
        lines.append(f"[{section}]")
        lines.append(f"token = {acc.get('token', '').strip()}")
        lines.append(f"user_id = {acc.get('user_id', '').strip()}")
        for extra in ("device_id", "label", "list_type", "app_ver", "apiv"):
            if acc.get(extra):
                lines.append(f"{extra} = {acc[extra]}")
        lines.append("")
    return "\n".join(lines)


def read_stdin_payload() -> dict:
    """Read a JSON object from stdin. Empty stdin is not an error."""
    if sys.stdin.isatty():
        return {}
    raw = sys.stdin.read().strip()
    if not raw:
        return {}
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"stdin is not valid JSON: {exc}") from None
    if not isinstance(payload, dict):
        raise SystemExit("stdin must be a JSON object")
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install kpl-stock-data credentials.")
    parser.add_argument("--root", help="writable root (default /workspace)")
    parser.add_argument("--dry-run", action="store_true", help="report only, write nothing")
    args = parser.parse_args(argv)

    payload = read_stdin_payload()
    if args.root:
        os.environ["KPLS_WORK_ROOT"] = args.root

    source = skill_source()
    root = writable_root()

    # ---- collect from env (preferred) and stdin -------------------------------
    found: dict[str, str] = {}
    for key, env_name in ENV_MAP.items():
        value = os.environ.get(env_name, "").strip()
        if value:
            found[key] = value
    for key in FILE_MAP:
        if payload.get(key):
            found[key] = str(payload[key])
    if payload.get("accounts"):
        found["accounts"] = payload["accounts"]

    # ---- report --------------------------------------------------------------
    print("kpl-stock-data credential setup")
    print(f"  skill source : {source}")
    print(f"  writable root: {root}")
    print()
    print("  discovered (values are never printed):")
    for key in ("kpl_accounts_ini", "kpl_accounts", "tushare_token", "py_token", "kpl_token", "kpl_user_id", "kpl_device_id"):
        mark = "yes" if found.get(key) else "-"
        print(f"    {key:18s} {mark}")
    if not any(found.get(k) for k in ("kpl_accounts", "kpl_accounts_ini", "kpl_token", "tushare_token", "py_token")):
        print()
        print("  nothing to install. Supply credentials via environment variables")
        print("  (KPL_ACCOUNTS_INI / TUSHARE_TOKEN / KPL_PY_TOKEN) or as a JSON object on stdin.")
        return 1

    if args.dry_run:
        print()
        print("  dry run: nothing written.")
        return 0

    # ---- stage --------------------------------------------------------------
    dest = stage_copy(source, root)
    assets = dest / "assets"
    print()
    print(f"  staged skill copy: {dest}")

    # ---- kpl accounts ------------------------------------------------------
    if found.get("accounts"):
        accounts = found["accounts"]
        if isinstance(accounts, str):
            accounts = [{"name": "main_self", "token": accounts.strip()}]
        ini_path = assets / "kpl_accounts.ini"
        ini_path.write_text(build_ini(accounts), encoding="utf-8")
        harden(ini_path)
        print(f"  wrote {ini_path} ({len(accounts)} account(s), mode 600)")
    elif found.get("kpl_accounts_ini"):
        ini_path = assets / "kpl_accounts.ini"
        ini_path.write_text(found["kpl_accounts_ini"].rstrip() + "\n", encoding="utf-8")
        harden(ini_path)
        print(f"  wrote {ini_path} (mode 600)")
    elif found.get("kpl_token") and found.get("kpl_user_id"):
        # Single-account fallback. config.accounts() reads KPL_TOKEN/KPL_USER_ID
        # from the environment, so this needs no file at all -- but writing the
        # ini keeps it working across sessions that do not export the vars.
        ini_path = assets / "kpl_accounts.ini"
        ini_path.write_text(
            build_ini(
                [
                    {
                        "name": "main_self",
                        "token": found["kpl_token"],
                        "user_id": found["kpl_user_id"],
                        "device_id": found.get("kpl_device_id", ""),
                    }
                ]
            ),
            encoding="utf-8",
        )
        harden(ini_path)
        print(f"  wrote {ini_path} (single account, mode 600)")

    # ---- tushare ------------------------------------------------------------
    if found.get("tushare_token"):
        token_path = assets / "tushare.token"
        write_secret(token_path, found["tushare_token"])
        print(f"  wrote {token_path} (mode 600)")

    # ---- platform token -----------------------------------------------------
    if found.get("py_token"):
        token_path = assets / "py_token.txt"
        write_secret(token_path, found["py_token"])
        print(f"  wrote {token_path} (mode 600)")

    print()
    print("  next: run the staged copy, not the /skills original")
    print(f"    cd {dest}")
    print(f"    python scripts/kpls.py doctor -v")
    return 0


if __name__ == "__main__":
    sys.exit(main())
